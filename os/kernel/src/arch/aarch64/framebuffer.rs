pub struct Framebuffer {
    address: usize,
    pitch: usize,
    width: usize,
    height: usize,
}

const GLYPH_WIDTH: usize = 5;
const GLYPH_HEIGHT: usize = 7;
const GLYPH_ADVANCE: usize = 6;
const LINE_ADVANCE: usize = 10;
const MARGIN_X: usize = 8;
const MARGIN_Y: usize = 8;

impl Framebuffer {
    pub fn new(address: usize, pitch: usize, width: usize, height: usize, bpp: usize) -> Option<Self> {
        if bpp != 32 {
            return None;
        }

        Some(Self {
            address,
            pitch,
            width,
            height,
        })
    }

    pub fn clear(&self, r: u8, g: u8, b: u8) {
        for y in 0..self.height {
            let row = self.address + y * self.pitch;
            for x in 0..self.width {
                self.write_pixel(row + x * 4, r, g, b);
            }
        }
    }

    pub fn write_line(&self, line: usize, text: &str) {
        let y = MARGIN_Y + line * LINE_ADVANCE;
        self.write_text(MARGIN_X, y, text);
    }

    pub fn write_text(&self, x: usize, y: usize, text: &str) {
        let mut cursor_x = x;

        for byte in text.bytes() {
            if byte == b'\n' {
                break;
            }

            self.draw_char(cursor_x, y, byte);
            cursor_x += GLYPH_ADVANCE;
            if cursor_x + GLYPH_WIDTH >= self.width {
                break;
            }
        }
    }

    pub fn write_hex_usize(&self, x: usize, y: usize, value: usize) {
        const HEX: &[u8; 16] = b"0123456789ABCDEF";
        let nybbles = core::mem::size_of::<usize>() * 2;
        let mut buffer = [b'0'; 2 + 16];
        buffer[0] = b'0';
        buffer[1] = b'X';

        for shift in 0..nybbles {
            let digit_shift = (nybbles - 1 - shift) * 4;
            let digit = (value >> digit_shift) & 0xf;
            buffer[2 + shift] = HEX[digit];
        }

        self.write_text(x, y, unsafe { core::str::from_utf8_unchecked(&buffer[..2 + nybbles]) });
    }

    fn draw_char(&self, x: usize, y: usize, byte: u8) {
        let glyph = glyph_rows(byte);

        for (row_index, row) in glyph.iter().enumerate() {
            for col in 0..GLYPH_WIDTH {
                if row & (1 << (GLYPH_WIDTH - 1 - col)) == 0 {
                    continue;
                }

                let px = x + col;
                let py = y + row_index;
                if px >= self.width || py >= self.height {
                    continue;
                }

                let offset = self.address + py * self.pitch + px * 4;
                self.write_pixel(offset, 0xff, 0xff, 0xff);
            }
        }
    }

    fn write_pixel(&self, offset: usize, r: u8, g: u8, b: u8) {
        let pixel = offset as *mut u8;
        unsafe {
            // Current firmware/QEMU path reports BGRX32.
            core::ptr::write_volatile(pixel, b);
            core::ptr::write_volatile(pixel.add(1), g);
            core::ptr::write_volatile(pixel.add(2), r);
            core::ptr::write_volatile(pixel.add(3), 0x00);
        }
    }
}

